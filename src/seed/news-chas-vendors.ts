const exists = await payload.find({ collection: 'articles', where: { title: { equals: TITLE } }, locale: 'hi', limit: 1, depth: 0, draft: true })
if (exists.docs[0]) {
  log('story already there — id', exists.docs[0].id)
  process.exit(0)
}

