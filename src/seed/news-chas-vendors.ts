const tagIds: number[] = []
for (const [slug, hi, en] of [
  ['jharkhand', 'झारखंड', 'Jharkhand'],
  ['bokaro', 'बोकारो', 'Bokaro'],
  ['chas', 'चास', 'Chas'],
  ['street-vendor', 'स्ट्रीट वेंडर', 'Street vendors'],
] as const)
  tagIds.push(await bilingual('tags', slug, { title: hi }, () => ({ title: en })))

const cat = await findSlug('categories', 'sawal-sarvajanik-hit-ka')
const a = await payload.create({
  collection: 'articles',
  locale: 'hi',
  data: {
    title: TITLE,
    subheadline: 'एक ही राज्य, एक ही विभाग, फिर दो शहरों के बीच सम्मान का इतना दोहरा मापदंड क्यों?',
    excerpt: 'रांची के वेंडरों को पक्की छत, पानी और शौचालय; बोकारो के चास में सैकड़ों छोटे दुकानदार आज भी धूप-बारिश में फुटपाथ पर।',
    category: cat?.id,
    heroImage: hero.id,
    content: paragraphsToLexical(P),
    location: 'चास, बोकारो (झारखंड)',
    reporterName: 'संपादकीय टीम',
    tags: tagIds,
    format: 'news',
    publishedAt: new Date().toISOString(),
    _status: 'published',
  } as never,
})
log('published — id', a.id, a.newsId)
process.exit(0)
